// Packs the desktop binaries for a GitHub release. Run after `npm run build:desktop`.
// Writes dist/<tag>/*.zip, macos/qvac_flutter/release.json and cmake/release.cmake.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { writePackageSwift } from './package_swift.mjs'

const root = import.meta.dirname
const plugin = path.resolve(root, '../..')
const pubspec = await readFile(path.join(plugin, 'pubspec.yaml'), 'utf8')
const repo = pubspec.match(/^repository:\s*https:\/\/github\.com\/(\S+)/m)[1]
// Separate from the mobile tag in release.mjs. Bump it when the desktop binaries change.
const tag = 'desktop-1'
const base = `https://github.com/${repo}/releases/download/${tag}`
const dist = path.join(root, 'dist', tag)
await rm(dist, { recursive: true, force: true })
await mkdir(dist, { recursive: true })

// macOS: one zip per xcframework, as Swift Package Manager binary targets need.
const macos = path.join(plugin, 'macos', 'qvac_flutter')
const frameworks = path.join(macos, 'Frameworks')
const mac = []
for (const file of (await readdir(frameworks)).filter((f) => f.endsWith('.xcframework')).sort()) {
  const zip = `macos-${file}.zip`
  // No resource forks or xattrs: SwiftPM unzips them as ._ files, which breaks the signature.
  execFileSync('ditto', ['-c', '-k', '--norsrc', '--noextattr', '--noacl', '--keepParent',
    path.join(frameworks, file), path.join(dist, zip)])
  const checksum = execFileSync('swift', ['package', 'compute-checksum', path.join(dist, zip)]).toString().trim()
  mac.push({ file, url: `${base}/${zip}`, checksum })
}
await writeFile(path.join(macos, 'release.json'), JSON.stringify(mac, null, 2) + '\n')
await writePackageSwift('release', 'macos')

// Linux and Windows: one flat zip each, which cmake/qvac_binaries.cmake unpacks.
const lines = ['# Generated by tool/worker/release_desktop.mjs. Do not edit by hand.']
for (const target of ['linux-x64', 'linux-arm64', 'windows-x64']) {
  const dir = path.join(plugin, 'build_desktop', target)
  const zip = `${target}.zip`
  execFileSync('zip', ['-q', '-X', path.join(dist, zip), ...(await readdir(dir)).sort()], { cwd: dir })
  const sha256 = createHash('sha256').update(await readFile(path.join(dist, zip))).digest('hex')
  lines.push(`set(QVAC_${target}_URL "${base}/${zip}")`, `set(QVAC_${target}_SHA256 "${sha256}")`)
}
await writeFile(path.join(plugin, 'cmake', 'release.cmake'), lines.join('\n') + '\n')

console.log(`Packed ${mac.length + 3} files into ${path.relative(plugin, dist)}`)
console.log(`Upload them with: gh release create ${tag} ${path.relative(plugin, dist)}/* --repo ${repo} --title ${tag}`)
