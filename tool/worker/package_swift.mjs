// Writes Package.swift with one binary target per framework. SwiftPM caches
// manifests by their text, so the manifest can't look at the disk itself.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ios = path.resolve(import.meta.dirname, '../../ios/qvac_flutter')

const targetName = (file) => file.replace(/\.xcframework$/, '').replace(/[^A-Za-z0-9]/g, '_')

/** 'local' uses ios/qvac_flutter/Frameworks; 'release' uses release.json URLs. */
export async function writePackageSwift(mode) {
  let targets
  if (mode === 'local') {
    const files = (await readdir(path.join(ios, 'Frameworks'))).filter((f) => f.endsWith('.xcframework')).sort()
    targets = files.map((f) => `        .binaryTarget(name: "${targetName(f)}", path: "Frameworks/${f}"),`)
  } else {
    const release = JSON.parse(await readFile(path.join(ios, 'release.json'), 'utf8'))
    targets = release.map((r) =>
      `        .binaryTarget(\n            name: "${targetName(r.file)}",\n            url: "${r.url}",\n            checksum: "${r.checksum}"\n        ),`)
  }
  const names = (mode === 'local'
    ? (await readdir(path.join(ios, 'Frameworks'))).filter((f) => f.endsWith('.xcframework')).sort()
    : JSON.parse(await readFile(path.join(ios, 'release.json'), 'utf8')).map((r) => r.file))
    .map((f) => `                "${targetName(f)}",`)

  await writeFile(path.join(ios, 'Package.swift'), `// swift-tools-version: 5.9
// Generated by tool/worker (${mode} binaries). Do not edit by hand.

import PackageDescription

let package = Package(
    name: "qvac_flutter",
    platforms: [
        .iOS("15.0")
    ],
    products: [
        .library(name: "qvac-flutter", targets: ["qvac_flutter"])
    ],
    dependencies: [
        .package(name: "FlutterFramework", path: "../FlutterFramework")
    ],
    targets: [
        .target(
            name: "qvac_flutter",
            dependencies: [
                .product(name: "FlutterFramework", package: "FlutterFramework"),
                // BareKit and the worker's addons. The worker loads each addon by
                // framework name, so all of them get embedded.
${names.join('\n')}
            ],
            resources: [
                .process("PrivacyInfo.xcprivacy"),
                .copy("Resources/worker.bundle"),
            ]
        ),
${targets.join('\n')}
    ]
)
`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writePackageSwift(process.argv[2] === 'local' ? 'local' : 'release')
}
