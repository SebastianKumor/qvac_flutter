// Writes Package.swift with one binary target per framework. SwiftPM caches
// manifests by their text, so the manifest can't look at the disk itself.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const plugin = path.resolve(import.meta.dirname, '../..')
const platforms = {
  ios: '.iOS("15.0")',
  // BareKit's macOS build needs macOS 13.
  macos: '.macOS("13.0")'
}

const targetName = (file) => file.replace(/\.xcframework$/, '').replace(/[^A-Za-z0-9]/g, '_')

/** 'local' uses <platform>/qvac_flutter/Frameworks; 'release' uses release.json URLs. */
export async function writePackageSwift(mode, platform = 'ios') {
  const dir = path.join(plugin, platform, 'qvac_flutter')
  const files = mode === 'local'
    ? (await readdir(path.join(dir, 'Frameworks'))).filter((f) => f.endsWith('.xcframework')).sort()
    : null
  const release = mode === 'local' ? null : JSON.parse(await readFile(path.join(dir, 'release.json'), 'utf8'))
  const targets = mode === 'local'
    ? files.map((f) => `        .binaryTarget(name: "${targetName(f)}", path: "Frameworks/${f}"),`)
    : release.map((r) =>
      `        .binaryTarget(\n            name: "${targetName(r.file)}",\n            url: "${r.url}",\n            checksum: "${r.checksum}"\n        ),`)
  const names = (files ?? release.map((r) => r.file)).map((f) => `                "${targetName(f)}",`)

  await writeFile(path.join(dir, 'Package.swift'), `// swift-tools-version: 5.9
// Generated by tool/worker (${mode} binaries). Do not edit by hand.

import PackageDescription

let package = Package(
    name: "qvac_flutter",
    platforms: [
        ${platforms[platform]}
    ],
    products: [
        .library(name: "qvac-flutter", targets: ["qvac_flutter"])
    ],
    dependencies: [
        .package(name: "FlutterFramework", path: "../FlutterFramework")
    ],
    targets: [
        .target(
            name: "qvac_flutter",
            dependencies: [
                .product(name: "FlutterFramework", package: "FlutterFramework"),
                // BareKit and the worker's addons. The worker loads each addon by
                // framework name, so all of them get embedded.
${names.join('\n')}
            ],
            resources: [
                .process("PrivacyInfo.xcprivacy"),
                .copy("Resources/worker.bundle"),
            ]
        ),
${targets.join('\n')}
    ]
)
`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [mode, ...only] = process.argv.slice(2)
  for (const platform of only.length ? only : Object.keys(platforms)) {
    await writePackageSwift(mode === 'local' ? 'local' : 'release', platform)
  }
}
